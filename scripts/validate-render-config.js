import { readFile } from 'node:fs/promises';
import { parse } from 'yaml';
import { fileURLToPath } from 'node:url';

export function validateRenderBlueprint(source) {
  const blueprint = parse(source);
  if (!blueprint || !Array.isArray(blueprint.services) || !Array.isArray(blueprint.databases)) {
    throw new Error('Blueprint must define services and databases.');
  }
  const service = blueprint.services.find(item => item.name === 'shiner-scents' && item.type === 'web');
  if (!service || service.runtime !== 'node') throw new Error('Blueprint must define the Shiner Scents Node web service.');
  if (service.plan === 'free') throw new Error('Product photo uploads need a paid web service with a persistent disk.');
  if (service.buildCommand !== 'npm ci' || service.startCommand !== 'npm start') {
    throw new Error('The web service must install from the lockfile and start with npm start.');
  }
  if (service.healthCheckPath !== '/healthz') throw new Error('The web service must check /healthz.');
  if (service.disk?.mountPath !== '/var/data' || Number(service.disk.sizeGB) < 1) {
    throw new Error('The web service must include a persistent disk mounted at /var/data.');
  }

  const database = blueprint.databases.find(item => item.name === 'shiner-scents-db');
  if (!database || database.region !== service.region) {
    throw new Error('The Render PostgreSQL database must be defined in the web service region.');
  }
  const envVars = Object.fromEntries((service.envVars || []).map(item => [item.key, item]));
  if (envVars.DATABASE_URL?.fromDatabase?.name !== database.name
      || envVars.DATABASE_URL.fromDatabase.property !== 'connectionString') {
    throw new Error('DATABASE_URL must use the Shiner Scents Render PostgreSQL connection string.');
  }
  if (envVars.SESSION_SECRET?.generateValue !== true) {
    throw new Error('SESSION_SECRET must be generated by Render.');
  }
  if (envVars.UPLOAD_DIR?.value !== '/var/data/uploads') {
    throw new Error('UPLOAD_DIR must be inside the persistent disk mount.');
  }
  if (envVars.NODE_ENV?.value !== 'production') throw new Error('NODE_ENV must be production.');
  for (const key of ['ADMIN_EMAIL', 'ADMIN_PASSWORD']) {
    if (envVars[key]?.sync !== false) throw new Error(`${key} must be entered privately in the Render Dashboard.`);
  }
  return blueprint;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    const source = await readFile(new URL('../render.yaml', import.meta.url), 'utf8');
    const blueprint = validateRenderBlueprint(source);
    console.log(`Render configuration is ready for ${blueprint.services[0].name}.`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
